/**
 * Makes src/web/brand.ts, the identity's files the site serves: the primary horizontal logo for
 * light and dark (`logo/lockup-horizontal-color.svg` and `-white.svg`, the green mark and the
 * Overpass wordmark as outlines) and the Highway icon (`icons/svg/highway.svg`), which is
 * /favicon.svg and what icons.ts draws the PNG icons from. The bundle has no folder of files, so
 * they go in as a module, byte for byte as the package has them.
 *
 *   npm run brand -- design/brand/v1
 *
 * Run it again when the package changes; a test checks the module still matches the package.
 */
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const [folder] = process.argv.slice(2);
if (!folder) {
  console.error('npm run brand -- <identity package folder, e.g. design/brand/v1>');
  process.exit(1);
}

const manifest = JSON.parse(await readFile(join(folder, 'manifest.json'), 'utf8')) as { version: string };
const version = `v${manifest.version.split('.')[0]}`;
const read = (path: string) => readFile(join(folder, path), 'utf8');
const [color, white, highway] = await Promise.all([
  read('logo/lockup-horizontal-color.svg'),
  read('logo/lockup-horizontal-white.svg'),
  read('icons/svg/highway.svg')
]);
const box = (svg: string) => {
  const [, w, h] = /viewBox="0 0 (\d+) (\d+)"/.exec(svg) ?? [];
  if (!w || !h) throw new Error('no viewBox');
  return { width: Number(w), height: Number(h) };
};

const out = new URL('../src/web/brand.ts', import.meta.url);
await writeFile(
  out,
  `// Generated by tools/brand.ts from the Road Sign Math identity package ${manifest.version}
// (design/brand/${version}): the files as supplied. Don't edit by hand; run \`npm run brand -- design/brand/${version}\`.

/** The package's version, in the address the logo files are served at (/brand/${version}/…). */
export const BRAND_VERSION = ${JSON.stringify(version)};
/** The primary horizontal logo's frame: the mark, the wordmark and the clear space around them. */
export const LOCKUP_SIZE = ${JSON.stringify(box(color))} as const;
/** The logo files the site serves, by name: green mark and ink words for light, all white for dark. */
export const BRAND_FILES = {
  'lockup-horizontal-color.svg': ${JSON.stringify(color)},
  'lockup-horizontal-white.svg': ${JSON.stringify(white)}
} as const;
/** The Highway icon, square and full bleed (a phone rounds its corners itself). */
export const HIGHWAY_SVG = ${JSON.stringify(highway)};
`
);
execFileSync('npx', ['prettier', '--write', out.pathname], { stdio: 'inherit' });
