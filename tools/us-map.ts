// Writes src/web/us-map.ts: the US as SVG paths in the 975 × 610 Albers USA frame that
// us-atlas's states-albers-10m is drawn in (the design's map). Run it with `npm run us-map`
// after changing it or us-atlas; the output is committed so the server reads no map data.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';

const require = createRequire(import.meta.url);
const us = JSON.parse(readFileSync(require.resolve('us-atlas/states-albers-10m.json'), 'utf8')) as Topology<{
  states: GeometryCollection;
  nation: GeometryCollection;
}>;

const path = geoPath().digits(1);
const land = path(feature(us, us.objects.nation)) ?? '';
const borders = path(mesh(us, us.objects.states, (a, b) => a !== b)) ?? '';

writeFileSync(
  new URL('../src/web/us-map.ts', import.meta.url),
  `// Generated by tools/us-map.ts from us-atlas ${require('us-atlas/package.json').version} (ISC, from the US Census Bureau's
// cartographic boundaries). Don't edit by hand.

/** The frame the paths are drawn in. */
export const US_MAP_SIZE = { width: 975, height: 610 } as const;
/** The country, one filled shape. */
export const US_LAND = ${JSON.stringify(land)};
/** The lines between states. */
export const US_BORDERS = ${JSON.stringify(borders)};
`
);
