/**
 * Makes src/quiz/checker.ts: the equation checker (src/domain/equation.ts) bundled for the
 * browser, so Quiz's keypad says "It works" with the same rules the server checks a way by. The
 * bundle is a script that sets `window.RSMCheck` to the checker's exports. The module also keeps
 * the SHA-256 of equation.ts it was made from, and a test fails when the two differ.
 *
 *   npm run quiz-checker
 *
 * Run it again whenever equation.ts changes.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const SOURCE = 'src/domain/equation.ts';

const source = await readFile(SOURCE, 'utf8');
const bundle = await build({
  entryPoints: [SOURCE],
  bundle: true,
  format: 'iife',
  globalName: 'RSMCheck',
  minify: true,
  target: 'es2020',
  legalComments: 'none',
  write: false
});
const code = bundle.outputFiles[0].text.trim();
const sha = createHash('sha256').update(source).digest('hex');

await writeFile(
  'src/quiz/checker.ts',
  `// Generated by \`npm run quiz-checker\` (tools/quiz-checker.ts) from ${SOURCE}. Don't edit it:
// change the checker and run the tool again.

/** The SHA-256 of the equation.ts this bundle was made from. */
export const CHECKER_SOURCE_SHA = ${JSON.stringify(sha)};

/** The checker as a browser script that sets \`window.RSMCheck\`. */
export const CHECKER_JS = ${JSON.stringify(code)};
`
);
console.log(`src/quiz/checker.ts: ${code.length} bytes from ${SOURCE}`);
